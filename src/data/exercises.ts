export function findExercise(id: string): ExerciseLibraryItem | undefined {
  return EXERCISE_LIBRARY.find((e) => e.id === id);
}

export const EXERCISE_LIBRARY_BY_MUSCLE = EXERCISE_LIBRARY.reduce<
  Record<string, ExerciseLibraryItem[]>
>((acc, ex) => {
  if (!acc[ex.muscleGroup]) acc[ex.muscleGroup] = [];
  acc[ex.muscleGroup].push(ex);
  return acc;
}, {});
